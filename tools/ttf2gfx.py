#!/usr/bin/env python3
"""TTF -> Adafruit_GFX font header.

Adafruit only ships Free* fonts at 9/12/18/24pt, and there is nothing between
9pt and the built-in 5x7. This produces the in-between sizes.

Glyph bitmaps are 1-bit, MSB first, packed *continuously* across the whole
glyph - rows are not byte-padded. That is the detail that silently corrupts
hand-rolled converters.
"""

import sys
from PIL import Image, ImageFont, ImageDraw

FIRST, LAST = 0x20, 0x7E


def render(font, ch):
    """Return (w, h, xoff, yoff, xadv, bits) for one character, unantialiased."""
    ascent, _ = font.getmetrics()
    box = font.getbbox(ch)
    xadv = int(round(font.getlength(ch)))

    if box is None or box[2] - box[0] <= 0 or box[3] - box[1] <= 0:
        return 0, 0, 0, 0, xadv, []                      # space and friends

    x0, y0, x1, y1 = box
    w, h = x1 - x0, y1 - y0

    img = Image.new("1", (w, h), 0)                      # mode "1" = no AA
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=1)
    px = img.load()

    bits = [1 if px[x, y] else 0 for y in range(h) for x in range(w)]
    return w, h, x0, y0 - ascent, xadv, bits             # yoff is from baseline


def build(path, size, name, index=0):
    font = ImageFont.truetype(path, size, index=index)
    ascent, descent = font.getmetrics()

    blob, glyphs = [], []
    for code in range(FIRST, LAST + 1):
        w, h, xo, yo, xadv, bits = render(font, chr(code))
        offset = len(blob)

        acc, nbits = 0, 0                                # pack continuously
        for b in bits:
            acc = (acc << 1) | b
            nbits += 1
            if nbits == 8:
                blob.append(acc); acc, nbits = 0, 0
        if nbits:
            blob.append(acc << (8 - nbits))

        glyphs.append((offset, w, h, xadv, xo, yo))

    out = [f"// Generated by tools/ttf2gfx.py from {path.split('/')[-1]} at {size}px",
           "#pragma once", "#include <Adafruit_GFX.h>", "",
           f"const uint8_t {name}Bitmaps[] PROGMEM = {{"]
    for i in range(0, len(blob), 12):
        out.append("  " + ", ".join(f"0x{b:02X}" for b in blob[i:i + 12]) + ",")
    out += ["};", "", f"const GFXglyph {name}Glyphs[] PROGMEM = {{"]
    for i, (off, w, h, xadv, xo, yo) in enumerate(glyphs):
        out.append(f"  {{ {off:5d}, {w:3d}, {h:3d}, {xadv:3d}, {xo:4d}, {yo:4d} }},"
                   f"   // 0x{FIRST + i:02X} '{chr(FIRST + i) if FIRST + i != 0x27 else ' '}'")
    out += ["};", "",
            f"const GFXfont {name} PROGMEM = {{",
            f"  (uint8_t *){name}Bitmaps,",
            f"  (GFXglyph *){name}Glyphs,",
            f"  0x{FIRST:02X}, 0x{LAST:02X}, {ascent + descent} }};", ""]
    return "\n".join(out), {"ascent": ascent, "yAdvance": ascent + descent}


if __name__ == "__main__":
    path, size, name, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
    index = int(sys.argv[5]) if len(sys.argv) > 5 else 0
    text, meta = build(path, size, name, index)
    open(out, "w").write(text)
    print(f"{out}: {name} ascent={meta['ascent']} yAdvance={meta['yAdvance']}")
